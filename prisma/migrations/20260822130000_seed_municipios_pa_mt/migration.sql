-- Corrige UF e comissão dos registros já existentes com o mesmo nome de município.
UPDATE "locais" l
SET
  "uf" = m.uf,
  "valorComissao" = m.valor,
  "updatedAt" = CURRENT_TIMESTAMP
FROM tmp_municipios_radasa m
WHERE LOWER(TRIM(l."cidade")) = LOWER(TRIM(m.cidade));

-- Insere apenas municípios que ainda não tenham cadastro na mesma UF.
INSERT INTO "locais" ("id", "cidade", "uf", "valorComissao", "createdAt", "updatedAt")
SELECT
  'municipio-' || LOWER(m.uf) || '-' || MD5(m.uf || ':' || m.cidade),
  m.cidade,
  m.uf,
  m.valor,
  CURRENT_TIMESTAMP,
  CURRENT_TIMESTAMP
FROM tmp_municipios_radasa m
WHERE NOT EXISTS (
  SELECT 1
  FROM "locais" l
  WHERE LOWER(TRIM(l."cidade")) = LOWER(TRIM(m.cidade))
    AND UPPER(COALESCE(l."uf", '')) = m.uf
);

-- Reforça a regra automática final das comissões.
UPDATE "locais"
SET "valorComissao" = CASE
  WHEN LOWER(TRIM(REGEXP_REPLACE("cidade", '\s*[/,-]\s*[A-Za-z]{2}\s*$', ''))) = 'colniza'
       AND UPPER(COALESCE("uf", 'MT')) = 'MT' THEN 350.00
  WHEN UPPER(COALESCE("uf", '')) = 'PA' THEN 300.00
  ELSE 275.00
END
WHERE UPPER(COALESCE("uf", '')) IN ('PA', 'MT');
